# Packs the assembled Outlaw puppet into one atlas + a rig description for the game (assets/rigs/outlaw.js).
import json, numpy as np, cv2
from PIL import Image
from rig_setup2 import *
OUT='/home/claude/the-lost-gold-train'
pl=placements()
RS=0.62                         # reference-sized layers are stored at this scale (they are large and soft anyway)
BONES={  # name: (parent, pivot on the reference canvas)
 'root':(None,(590,1550)), 'body':('root',(590,650)), 'head':('body',(548,300)),
 'relax_up':('body',(705,470)), 'relax_fore':('relax_up',(748,615)), 'relax_hand':('relax_fore',(785,745)),
 'aim_fore':('body',(445,470)), 'aim_hand':('aim_fore',(585,425)),
}
LAYER_BONE={'poncho_ref_main':'body','poncho_ref_tail':'body','arm_relaxed_upper':'relax_up','arm_relaxed_forearm':'relax_fore','hand_relaxed':'relax_hand',
 'torso':'body','lowerbody_ref':'root','arm_aim_upper':'body','neck_connector':'body','head':'head','poncho_ref_front':'body','hat':'head',
 'arm_aim_forearm':'aim_fore','revolver':'aim_hand','hand_aim':'aim_hand'}
CLOTH={'poncho_ref_main':{'root':[420,262],'amp':1.0},'poncho_ref_tail':{'root':[705,450],'amp':.7},'poncho_ref_front':{'root':[520,250],'amp':.25}}
imgs=[]
for k in ORDER:
    im=Image.open(fname(k)).convert('RGBA'); a=np.asarray(im); ys,xs=np.where(a[...,3]>8)
    x0,y0,x1,y1=xs.min(),ys.min(),xs.max()+1,ys.max()+1; crop=im.crop((x0,y0,x1,y1))
    T=np.array(pl[k],dtype=float); T=np.vstack([T,[0,0,1]]) @ np.array([[1,0,x0],[0,1,y0],[0,0,1]])   # crop offset
    if k in REF:
        crop=crop.resize((max(1,round(crop.width*RS)),max(1,round(crop.height*RS))),Image.LANCZOS); T=T@np.diag([1/RS,1/RS,1])
    imgs.append((k,crop,T[:2].tolist()))
# shelf-pack into one atlas
imgs_sorted=sorted(imgs,key=lambda t:-t[1].height); AW=2048; x=y=rowh=0; rects={}
for k,im,_ in imgs_sorted:
    if x+im.width+2>AW: x=0; y+=rowh+2; rowh=0
    rects[k]=[x,y,im.width,im.height]; x+=im.width+2; rowh=max(rowh,im.height)
AH=y+rowh; atlas=Image.new('RGBA',(AW,AH),(0,0,0,0))
for k,im,_ in imgs: atlas.paste(im,tuple(rects[k][:2]))
atlas.save(OUT+'/assets/images/characters/char_outlaw_parts.webp',quality=90,method=6)
ref=np.asarray(R)[...,3]; ys,xs=np.where(ref>20)
rig={'canvas':[W,H],'frame':[int(xs.min()),int(ys.min()),int(xs.max()+1),int(ys.max()+1)],
 'bones':{b:{'parent':p,'pivot':list(v)} for b,(p,v) in BONES.items()},
 'layers':[{'id':k,'rect':rects[k],'T':[[round(v,5) for v in r] for r in T],'bone':LAYER_BONE[k],**({'cloth':CLOTH[k]} if k in CLOTH else {})} for k,_,T in imgs],
 'anchors':{'tip':{'bone':'aim_hand','xy':[771,236]},'mouth':{'bone':'head','xy':[585,262]}}}
open(OUT+'/assets/rigs/outlaw.js','w').write('// Outlaw cutout rig: generated by tools/asset-pipeline/puppet/build_puppet.py from the parts atlas + reference cut layers.\n// Coordinates are on the 1060 x 1584 reference canvas; layers draw in this order.\n(typeof window !== "undefined" ? window : globalThis).RIGS = Object.assign((typeof window !== "undefined" ? window : globalThis).RIGS || {}, { outlaw: '+json.dumps(rig)+' });\n')
print('atlas',AW,AH, 'layers',len(imgs))
